import JSZip from 'jszip';
import { GeneratedFile } from '../types';

export async function exportCodebaseAsZip(files: GeneratedFile[], projectName: string) {
  const zip = new JSZip();
  const folderName = (projectName || 'ai-software-factory').toLowerCase().replace(/[^a-z0-9]/g, '-');
  const root = zip.folder(folderName) || zip;

  for (const file of files) {
    root.file(file.path, file.content);
  }

  // Add README.md if not present
  if (!files.some(f => f.path.toLowerCase().includes('readme'))) {
    root.file(
      'README.md',
      `# ${projectName}\n\nGenerated by **ApexForge AI Software Factory**.\n\n## Structure\n- \`backend/\`: Python FastAPI microservice architecture.\n- \`frontend/\`: React & Tailwind CSS application.\n- \`architecture/\`: Microservices blueprint, ADR, and communication topology.\n- \`tests/\`: Pytest test suite.\n\n## Running the Backend\n\`\`\`bash\ncd backend\npip install -r requirements.txt\nuvicorn main:app --reload --port 8000\n\`\`\`\n\n## Running the Frontend\n\`\`\`bash\ncd frontend\nnpm install\nnpm run dev\n\`\`\`\n`
    );
  }

  const content = await zip.generateAsync({ type: 'blob' });
  const downloadUrl = URL.createObjectURL(content);
  const anchor = document.createElement('a');
  anchor.href = downloadUrl;
  anchor.download = `${folderName}-codebase.zip`;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(downloadUrl);
}
